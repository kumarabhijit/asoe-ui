#!/usr/bin/env node
// Walks src/lib/api.ts for every http<T>("/api/...") and
// http<T>(`/api/...`) callsite. Normalises template placeholders
// (`/api/v1/exceptions/${id}`) to the OpenAPI placeholder form
// (`/api/v1/exceptions/{exception_id}`) by matching against the
// sibling asoe2 OpenAPI document's path list.
//
// Output: tests/contract/snapshots/ui_route_surface.json — array of
// every path the UI calls. Method-level conformance is a follow-on;
// path-level is the high-value check today (catches "UI calls a
// route the backend never exposed" and "backend retired a route the
// UI still calls").
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");
const API_TS = resolve(REPO_ROOT, "src/lib/api.ts");
const OPENAPI_PATH = resolve(REPO_ROOT, "..", "asoe2", "openapi", "asoe2.openapi.json");
const SNAPSHOT_PATH = resolve(REPO_ROOT, "tests/contract/snapshots/ui_route_surface.json");

if (!existsSync(OPENAPI_PATH)) {
  console.error(`[extract-ui-routes] sibling OpenAPI not found at ${OPENAPI_PATH}`);
  process.exit(1);
}

const src = readFileSync(API_TS, "utf-8");
const openapi = JSON.parse(readFileSync(OPENAPI_PATH, "utf-8"));
const openapiPaths = Object.keys(openapi.paths ?? {}).sort();

// Capture every string literal (single quote, double quote, or
// backtick) handed to http<T>(...).
const HTTP_CALL_RE = /\bhttp\s*<\s*[A-Za-z_][A-Za-z0-9_<>,\s]*\s*>\s*\(\s*(["`])((?:\\.|(?!\1).)*)\1/g;

function normalisePath(raw) {
  // Replace `${...}` (template) with a unique placeholder, then
  // resolve segment-by-segment against the OpenAPI path list.
  if (raw.indexOf("${") === -1) return raw;
  const skeleton = raw.replace(/\$\{[^}]+\}/g, "{}");
  for (const oapi of openapiPaths) {
    const oapiSkeleton = oapi.replace(/\{[^}]+\}/g, "{}");
    if (oapiSkeleton === skeleton) return oapi;
  }
  return skeleton.replace(/\{\}/g, "{id}");
}

const seen = new Map();
let m;
while ((m = HTTP_CALL_RE.exec(src)) !== null) {
  const raw = m[2];
  if (!raw.startsWith("/api/")) continue;
  const normalised = normalisePath(raw);
  if (!seen.has(normalised)) seen.set(normalised, { path: normalised, raw });
}

const routes = [...seen.values()].sort((a, b) =>
  a.path < b.path ? -1 : a.path > b.path ? 1 : 0,
);

const snapshot = {
  _source: "src/lib/api.ts",
  _oracle: "../asoe2/openapi/asoe2.openapi.json",
  _captured_at_utc: new Date().toISOString().slice(0, 10),
  _note:
    "Generated by scripts/extract-ui-routes.mjs. Each entry is a route " +
    "the UI client calls. The conformance test " +
    "(tests/contract/test_ui_route_conformance.test.ts) asserts each " +
    "path exists in the OpenAPI document.",
  routes,
};

mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
writeFileSync(SNAPSHOT_PATH, JSON.stringify(snapshot, null, 2) + "\n", "utf-8");

console.log(
  `[extract-ui-routes] wrote ${SNAPSHOT_PATH}\n` +
  `[extract-ui-routes] routes=${routes.length}, openapi-paths=${openapiPaths.length}`,
);
