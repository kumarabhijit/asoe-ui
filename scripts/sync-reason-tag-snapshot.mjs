#!/usr/bin/env node
// Parses asoe2/constraints/specs.py and writes the curated reason-tag
// snapshot (JSON) + the generated TS module (the mock consumes).
//
// Sibling-checkout pattern: reads ../asoe2/constraints/specs.py
// (same convention as `generate-types`, which reads
// ../asoe2/openapi/asoe2.openapi.json).
//
// Output files:
//   tests/contract/snapshots/curated_reason_tags.json
//   src/lib/__generated__/curated_reason_tags.ts
//
// Failure modes:
//   * sibling repo missing  -> exit 1 with a pointer
//   * specs.py missing     -> exit 1
//   * AllowedOverrideReasonTag literal not found -> exit 1
//   * _CURATED_INTENT_REASON_TAGS dict not found -> exit 1
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");
const SIBLING = resolve(REPO_ROOT, "..", "asoe2");
const SPECS_PATH = resolve(SIBLING, "constraints", "specs.py");

if (!existsSync(SIBLING)) {
  console.error(
    `[sync-reason-tag-snapshot] sibling checkout not found at ${SIBLING}.\n` +
    "Clone kumarabhijit/asoe2 as a sibling working tree, then re-run.",
  );
  process.exit(1);
}
if (!existsSync(SPECS_PATH)) {
  console.error(`[sync-reason-tag-snapshot] ${SPECS_PATH} missing.`);
  process.exit(1);
}

const SRC = readFileSync(SPECS_PATH, "utf-8");

// 1. Parse every `_FOO_REASON_TAGS: tuple[str, ...] = ( ... )` block.
//    Captures the constant name and the array of quoted strings.
const TUPLE_RE = /^(_[A-Z][A-Z0-9_]*_REASON_TAGS):\s*tuple\[str,\s*\.\.\.\]\s*=\s*\(([\s\S]*?)\n\)/gm;
const STRING_RE = /"([^"\\]+)"/g;
const TUPLES = new Map();
for (const m of SRC.matchAll(TUPLE_RE)) {
  const name = m[1];
  const body = m[2];
  const values = [...body.matchAll(STRING_RE)].map((x) => x[1]);
  if (values.length === 0) {
    console.error(`[sync-reason-tag-snapshot] tuple ${name} parsed empty.`);
    process.exit(1);
  }
  TUPLES.set(name, values);
}
if (!TUPLES.has("_GLOBAL_REASON_TAGS")) {
  console.error("[sync-reason-tag-snapshot] _GLOBAL_REASON_TAGS not found.");
  process.exit(1);
}
const GLOBAL_REASON_TAGS = TUPLES.get("_GLOBAL_REASON_TAGS");

// 2. Parse `_CURATED_INTENT_REASON_TAGS: dict[...] = { INTENT: _NAME, ... }`.
const DICT_RE = /_CURATED_INTENT_REASON_TAGS:\s*dict\[str,\s*tuple\[str,\s*\.\.\.\]\]\s*=\s*\{([\s\S]*?)^\}/m;
const dictMatch = SRC.match(DICT_RE);
if (!dictMatch) {
  console.error("[sync-reason-tag-snapshot] _CURATED_INTENT_REASON_TAGS dict not found.");
  process.exit(1);
}
const DICT_ENTRY_RE = /"([A-Z][A-Z0-9_]+)"\s*:\s*(_[A-Z][A-Z0-9_]*_REASON_TAGS)/g;
const CURATED = {};
for (const m of dictMatch[1].matchAll(DICT_ENTRY_RE)) {
  const intent = m[1];
  const constName = m[2];
  const vocab = TUPLES.get(constName);
  if (!vocab) {
    console.error(`[sync-reason-tag-snapshot] dict references unknown tuple ${constName} for intent ${intent}.`);
    process.exit(1);
  }
  CURATED[intent] = vocab;
}
if (Object.keys(CURATED).length === 0) {
  console.error("[sync-reason-tag-snapshot] curated dict parsed empty.");
  process.exit(1);
}

// 3. Parse `AllowedOverrideReasonTag = Literal[ ... ]` for the full union
//    (legacy lowercase + every curated UPPERCASE value).
const LITERAL_RE = /^AllowedOverrideReasonTag\s*=\s*Literal\[([\s\S]*?)^\]/m;
const literalMatch = SRC.match(LITERAL_RE);
if (!literalMatch) {
  console.error("[sync-reason-tag-snapshot] AllowedOverrideReasonTag Literal not found.");
  process.exit(1);
}
const ALL_TAGS = [...literalMatch[1].matchAll(STRING_RE)].map((x) => x[1]);
if (ALL_TAGS.length === 0) {
  console.error("[sync-reason-tag-snapshot] AllowedOverrideReasonTag Literal parsed empty.");
  process.exit(1);
}

// 4. Cross-check: every curated value must also appear in the Literal union.
//    Asoe2's `AllowedOverrideReasonTag` is the wire envelope; an entry only
//    in the curated dict but not in the Literal means asoe2 itself is
//    inconsistent (and the test that asserts byte-parity would fail).
const allTagSet = new Set(ALL_TAGS);
for (const [intent, vocab] of Object.entries(CURATED)) {
  for (const tag of vocab) {
    if (!allTagSet.has(tag)) {
      console.error(
        `[sync-reason-tag-snapshot] tag "${tag}" appears in curated ${intent}` +
        " vocab but not in AllowedOverrideReasonTag Literal. Fix asoe2 first.",
      );
      process.exit(1);
    }
  }
}

// 5. Emit snapshot JSON. Keys ordered stably; values preserved verbatim so
//    `tests/contract/test_reason_tag_vocab_parity.test.ts` can byte-diff.
const SNAPSHOT = {
  _source: "../asoe2/constraints/specs.py",
  _captured_at_utc: new Date().toISOString().slice(0, 10),
  _note:
    "Generated by scripts/sync-reason-tag-snapshot.mjs. Do not edit by hand; " +
    "re-run `npm run sync:reason-tags` to refresh from the sibling repo.",
  allowed_override_reason_tags: ALL_TAGS,
  allowed_override_reason_tags_by_intent: Object.fromEntries(
    Object.keys(CURATED).sort().map((k) => [k, CURATED[k]]),
  ),
  // Legacy global pool (lowercase). Used by is_valid_reason_tag_for_write
  // as the fallback when the intent has no curated vocab.
  legacy_global_reason_tags: GLOBAL_REASON_TAGS,
};

const SNAPSHOT_PATH = resolve(REPO_ROOT, "tests/contract/snapshots/curated_reason_tags.json");
mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
writeFileSync(SNAPSHOT_PATH, JSON.stringify(SNAPSHOT, null, 2) + "\n", "utf-8");

// 6. Emit the TS module the mock consumes.
const TS_PATH = resolve(REPO_ROOT, "src/lib/__generated__/curated_reason_tags.ts");
mkdirSync(dirname(TS_PATH), { recursive: true });
const ts = [
  "// AUTO-GENERATED — do not edit by hand.",
  "// Source: ../asoe2/constraints/specs.py",
  `// Regenerate with: npm run sync:reason-tags`,
  "",
  `export const ALLOWED_OVERRIDE_REASON_TAGS = ${JSON.stringify(ALL_TAGS, null, 2)} as const;`,
  "",
  `export const ALLOWED_OVERRIDE_REASON_TAGS_BY_INTENT: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(
    SNAPSHOT.allowed_override_reason_tags_by_intent,
    null,
    2,
  )};`,
  "",
  `export const LEGACY_GLOBAL_REASON_TAGS = ${JSON.stringify(GLOBAL_REASON_TAGS, null, 2)} as const;`,
  "",
  "export type CuratedIntent = keyof typeof ALLOWED_OVERRIDE_REASON_TAGS_BY_INTENT;",
  "",
].join("\n");
writeFileSync(TS_PATH, ts, "utf-8");

console.log(
  `[sync-reason-tag-snapshot] wrote ${SNAPSHOT_PATH}\n` +
  `[sync-reason-tag-snapshot] wrote ${TS_PATH}\n` +
  `[sync-reason-tag-snapshot] union=${ALL_TAGS.length}, intents=${Object.keys(CURATED).length}`,
);
